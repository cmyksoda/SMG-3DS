#!/usr/bin/env python3
"""Writes source/compat/Sdk.cpp: a loud stop for each Wii SDK C function the probe link of
tools/petari-link-needs.sh leaves undefined (its probe-undefined.txt), grouped by library.

usage: sdk-boundaries.py OUT_DIR/probe-undefined.txt > source/compat/Sdk.cpp
"""
import collections, re, sys

names = [line.split(maxsplit=1)[1].strip() for line in open(sys.argv[1]) if line.strip()]
# C functions only: members and data need their real types, and are handled where they belong.
functions = sorted({n for n in names if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n) and n not in {"__OSBusClock", "GXWGFifo"}})
groups = collections.defaultdict(list)
for name in functions:
    library = re.match(r"_*(C_MTX|PSMTX|THPGX|NWC24|WPAD|KPAD|NAND|WENC|[A-Z][A-Z]+(?=[A-Z][a-z0-9]|$)|[A-Z][a-z]+)", name)
    groups[library.group(1) if library else name].append(name)

print("""// Generated by tools/sdk-boundaries.py from a probe link of MarioActor (tools/petari-link-needs.sh): the Wii SDK
// functions the game's reachable code calls that the port has no body for yet. Each stops the program by name.
// No SDK header is included: C linkage matches by name alone, and none of these ever returns.
#include <cstdio>
#include <cstdlib>

namespace {
[[noreturn]] void unported(const char* name) {
    std::fprintf(stderr, "The Wii SDK's %s is not the port's yet\\n", name);
    std::abort();
}
} // namespace

extern "C" {""")
for library in sorted(groups):
    print(f"// {library}")
    for name in groups[library]:
        print(f'void {name}() {{ unported("{name}"); }}')
print("}")
